#Requires -Version 5.1
<#
.SYNOPSIS
    4NEC2 MCP Server 一键安装脚本（Windows PowerShell 5.1 / PowerShell 7 均可）。

.DESCRIPTION
    本脚本做以下几件事：
      1. 检查项目目录、mcp_4nec2_server.py、4NEC2 目录与 nec2 引擎是否存在；
      2. 创建（或复用）项目 venv：<项目>\.venv；
      3. 安装 requirements.txt 依赖（默认 mcp>=1.28,<2）；
      4. 用 `python mcp_4nec2_server.py --version` 做冒烟测试；
      5. 生成两个启动器：scripts\start-stdio.bat、scripts\start-http.bat（写入绝对路径）；
      6. 打印 DeepSeek Harness（DSH）的 cordis.patch.yml 配置条目文本。

    对 DSH 配置文件的操作默认**只打印不写入**。加 -ApplyDsh 才会把条目追加到
    <ProfileDir>\cordis.patch.yml（默认 C:\Users\<你>\.dsh\profiles\desktop\cordis.patch.yml）。
    写入前会自动备份为 cordis.patch.yml.bak-yyyyMMdd-HHmmss，且做幂等检查
    （已存在 id: mcp-4nec2 或 serverName: nec2 时跳过）。

.PARAMETER Nec2Dir
    4NEC2 安装目录，默认取环境变量 NEC4NEC_DIR，否则 C:\4nec2。
    nec2 引擎必须位于 <Nec2Dir>\exe 下（例如 nec2dxs11k.exe）。

.PARAMETER ProjectDir
    本项目根目录，默认为本脚本的上一级目录，即 C:\4nec2-mcp-server。

.PARAMETER ProfileDir
    DSH 配置目录，默认为 <用户目录>\.dsh\profiles\desktop。

.PARAMETER PythonExe
    用于创建 venv 的 Python 解释器；默认自动查找 python，其次 py -3。

.PARAMETER HttpHost
    HTTP 传输模式监听地址，默认 127.0.0.1（写入 start-http.bat）。

.PARAMETER HttpPort
    HTTP 传输模式监听端口，默认 8765（写入 start-http.bat）。

.PARAMETER ApplyDsh
    真正把 DSH 配置条目追加到 cordis.patch.yml（默认只打印）。

.PARAMETER NoDsh
    完全不输出 DSH 配置条目（只装环境）。

.PARAMETER SkipPip
    跳过 pip install 步骤（依赖已装好时可用）。

.PARAMETER SkipEngineCheck
    跳过 4NEC2 引擎存在性检查。

.PARAMETER Force
    venv 已存在时，把旧 venv 重命名为 .venv.bak-yyyyMMdd-HHmmss 后重建。
    注意：不会删除旧 venv，确认无误后可自行删除备份。

.PARAMETER DryRun
    只检查与打印将要执行的命令，不执行任何写操作（不建 venv、不装包、不写文件）。

.PARAMETER Utf8Console
    把控制台输出编码设为 UTF-8。仅当控制台中文乱码时使用；
    若使用后反而乱码，请改用 chcp 936 后再运行。

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts\install.ps1

    默认安装（只打印 DSH 条目，不改任何 DSH 配置）。

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts\install.ps1 -ApplyDsh

    安装并自动把 mcp-4nec2 条目写入 cordis.patch.yml（自动备份、幂等）。

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts\install.ps1 -Nec2Dir D:\4nec2 -HttpPort 9000 -DryRun

    自定义 4NEC2 目录与端口，只看会做什么。
#>
[CmdletBinding()]
param(
    [string]$Nec2Dir = $(if ($env:NEC4NEC_DIR) { $env:NEC4NEC_DIR } else { 'C:\4nec2' }),
    [string]$ProjectDir = '',
    [string]$ProfileDir = '',
    [string]$PythonExe = '',
    [string]$HttpHost = '127.0.0.1',
    [int]$HttpPort = 8765,
    [switch]$ApplyDsh,
    [switch]$NoDsh,
    [switch]$SkipPip,
    [switch]$SkipEngineCheck,
    [switch]$Force,
    [switch]$DryRun,
    [switch]$Utf8Console
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

if ($Utf8Console) {
    try {
        [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false)
    } catch {
        Write-Host "[warn] 无法设置 UTF-8 控制台编码，继续。" -ForegroundColor Yellow
    }
}

$script:StepNo = 0

function Write-Step {
    param([string]$Message)
    $script:StepNo = $script:StepNo + 1
    Write-Host ''
    Write-Host ('[{0}] {1}' -f $script:StepNo, $Message) -ForegroundColor Cyan
}

function Write-Ok {
    param([string]$Message)
    Write-Host ('  + ' + $Message) -ForegroundColor Green
}

function Write-Info {
    param([string]$Message)
    Write-Host ('    ' + $Message)
}

function Write-Warn {
    param([string]$Message)
    Write-Host ('  ! ' + $Message) -ForegroundColor Yellow
}

function Write-Fail {
    param([string]$Message)
    throw $Message
}

function Write-Plan {
    param([string]$Message)
    Write-Host ('  > ' + $Message) -ForegroundColor DarkGray
}

# 执行外部命令；DryRun 时只打印。返回退出码。
function Invoke-Native {
    param(
        [string]$FilePath,
        [string[]]$Arguments,
        [string]$Display
    )
    if ($DryRun) {
        Write-Plan ("{0} {1}" -f $FilePath, ($Arguments -join ' '))
        return 0
    }
    # 注意：$ErrorActionPreference=Stop 时，原生程序写 stderr 会抛 NativeCommandError；
    # 这里临时放宽并合并 stderr，避免 pip 等工具的普通提示被当成致命错误。
    $prevEap = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & $FilePath @Arguments 2>&1 | Out-Host
        $code = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $prevEap
    }
    return $code
}

# 生成 ASCII + CRLF 的 .bat 启动器
# 说明：.bat 内一律用英文注释与提示。cmd.exe 按 OEM 代码页解析批处理，
# 中文会显示成 ????，而且带 BOM 的 .bat 可能被 cmd 误读首行。
function Write-BatchFile {
    param(
        [string]$Path,
        [string]$Title,
        [string]$Mode = 'stdio'
    )

    $lines = @(
        '@echo off',
        ('rem {0}' -f $Title),
        'rem Generated by scripts\install.ps1 - re-run install.ps1 to regenerate.',
        'setlocal',
        ('set "NEC4NEC_DIR={0}"' -f $Nec2DirPath),
        ('set "PY={0}"' -f $VenvPython),
        ('set "SERVER={0}"' -f $ServerScript)
    )

    $transportArgs = '--transport stdio'
    if ($Mode -eq 'http') {
        $lines += ('if not defined MCP_HTTP_HOST set "MCP_HTTP_HOST={0}"' -f $HttpHost)
        $lines += ('if not defined MCP_HTTP_PORT set "MCP_HTTP_PORT={0}"' -f $HttpPort)
        $transportArgs = '--transport streamable-http --host %MCP_HTTP_HOST% --port %MCP_HTTP_PORT%'
    }

    $lines += 'if not exist "%PY%" ('
    $lines += '  echo [ERROR] venv python not found: %PY%'
    $lines += '  echo         run scripts\install.ps1 first.'
    $lines += '  exit /b 1'
    $lines += ')'
    $lines += 'if not exist "%SERVER%" ('
    $lines += '  echo [ERROR] server script not found: %SERVER%'
    $lines += '  exit /b 1'
    $lines += ')'
    $lines += ''
    $lines += ('"%PY%" "%SERVER%" --4nec2-dir "%NEC4NEC_DIR%" ' + $transportArgs + ' %*')
    $lines += 'endlocal'

    $text = ($lines -join "`r`n") + "`r`n"
    if ($DryRun) {
        Write-Plan ('生成 ' + $Path)
        return
    }
    $ascii = New-Object System.Text.ASCIIEncoding
    [System.IO.File]::WriteAllText($Path, $text, $ascii)
    Write-Ok ('已生成 ' + $Path)
}

function Get-Utf8NoBom {
    return New-Object System.Text.UTF8Encoding($false)
}

# ---------------------------------------------------------------------------
# 1. 路径解析与前置检查
# ---------------------------------------------------------------------------
Write-Host ''
Write-Host '============================================================' -ForegroundColor White
Write-Host ' 4NEC2 MCP Server 安装脚本' -ForegroundColor White
Write-Host '============================================================' -ForegroundColor White
if ($DryRun) {
    Write-Warn 'DryRun 模式：只检查与打印，不执行任何写操作。'
}

if ([string]::IsNullOrWhiteSpace($ProjectDir)) {
    $ProjectDir = Split-Path -Parent $PSScriptRoot
}
if ([string]::IsNullOrWhiteSpace($ProfileDir)) {
    $ProfileDir = Join-Path (Join-Path $env:USERPROFILE '.dsh\profiles') 'desktop'
}

$ProjectDirPath = [System.IO.Path]::GetFullPath($ProjectDir)
$Nec2DirPath = [System.IO.Path]::GetFullPath($Nec2Dir)
$ProfileDirPath = [System.IO.Path]::GetFullPath($ProfileDir)
$ServerScript = Join-Path $ProjectDirPath 'mcp_4nec2_server.py'
$Requirements = Join-Path $ProjectDirPath 'requirements.txt'
$VenvDir = Join-Path $ProjectDirPath '.venv'
$VenvPython = Join-Path $VenvDir 'Scripts\python.exe'
$ScriptsDir = Join-Path $ProjectDirPath 'scripts'
$DshConfig = Join-Path $ProfileDirPath 'cordis.patch.yml'

Write-Step '检查项目与 4NEC2 环境'
Write-Info ('项目目录   : ' + $ProjectDirPath)
Write-Info ('4NEC2 目录 : ' + $Nec2DirPath)
Write-Info ('venv       : ' + $VenvDir)
if (-not $NoDsh) {
    Write-Info ('DSH 配置   : ' + $DshConfig)
}

if (-not (Test-Path -LiteralPath $ProjectDirPath -PathType Container)) {
    Write-Fail ('项目目录不存在: ' + $ProjectDirPath)
}
if (-not (Test-Path -LiteralPath $ServerScript -PathType Leaf)) {
    Write-Fail ('找不到服务入口: ' + $ServerScript)
}
Write-Ok 'mcp_4nec2_server.py 存在'

if (-not (Test-Path -LiteralPath $Nec2DirPath -PathType Container)) {
    Write-Fail ('4NEC2 目录不存在: ' + $Nec2DirPath + '（用 -Nec2Dir 指定）')
}
$exeDir = Join-Path $Nec2DirPath 'exe'
# 写进 DSH 条目 env.NEC2_ENGINE 的引擎路径；默认按最常见文件名推断。
$EnginePath = Join-Path $exeDir 'nec2dxs11k.exe'
if (-not $SkipEngineCheck) {
    $engineCandidates = @()
    if (Test-Path -LiteralPath $exeDir -PathType Container) {
        $engineCandidates = @(Get-ChildItem -LiteralPath $exeDir -Filter 'nec2d*.exe' -File -ErrorAction SilentlyContinue)
    }
    if ($engineCandidates.Count -eq 0) {
        Write-Fail ('在 ' + $exeDir + ' 下找不到 nec2d*.exe 引擎；确认 4NEC2 安装在 ' + $Nec2DirPath + '，或加 -SkipEngineCheck')
    }
    $preferred = $engineCandidates | Where-Object { $_.Name -eq 'nec2dxs11k.exe' } | Select-Object -First 1
    if ($null -eq $preferred) {
        $preferred = $engineCandidates[0]
    }
    $EnginePath = $preferred.FullName
    Write-Ok ('找到 nec2 引擎，首选: ' + $EnginePath)
}

# ---------------------------------------------------------------------------
# 2. Python 解释器与 venv
# ---------------------------------------------------------------------------
Write-Step '准备 Python venv'

function Resolve-BasePython {
    if (-not [string]::IsNullOrWhiteSpace($PythonExe)) {
        if (-not (Test-Path -LiteralPath $PythonExe)) {
            Write-Fail ('指定的 -PythonExe 不存在: ' + $PythonExe)
        }
        return @{ Exe = $PythonExe; PreArgs = @(); Label = $PythonExe }
    }
    $cmd = Get-Command python -ErrorAction SilentlyContinue
    if ($null -ne $cmd) {
        return @{ Exe = $cmd.Source; PreArgs = @(); Label = $cmd.Source }
    }
    $cmd = Get-Command py -ErrorAction SilentlyContinue
    if ($null -ne $cmd) {
        return @{ Exe = $cmd.Source; PreArgs = @('-3'); Label = ($cmd.Source + ' -3') }
    }
    Write-Fail '找不到 python 或 py。请安装 Python 3.9+ 或用 -PythonExe 指定解释器路径。'
}

$hasVenv = Test-Path -LiteralPath $VenvPython -PathType Leaf

if ($hasVenv -and $Force) {
    $backupVenv = $VenvDir + '.bak-' + (Get-Date -Format 'yyyyMMdd-HHmmss')
    if ($DryRun) {
        Write-Plan ('重命名 ' + $VenvDir + ' -> ' + $backupVenv)
    } else {
        Move-Item -LiteralPath $VenvDir -Destination $backupVenv
        Write-Ok ('旧 venv 已重命名为 ' + $backupVenv)
    }
    $hasVenv = $false
}

if ($hasVenv) {
    Write-Ok ('复用已有 venv: ' + $VenvPython)
} else {
    $base = Resolve-BasePython
    Write-Info ('基础解释器: ' + $base.Label)
    $venvArgs = @()
    $venvArgs += $base.PreArgs
    $venvArgs += @('-m', 'venv', $VenvDir)
    $rc = Invoke-Native -FilePath $base.Exe -Arguments $venvArgs -Display 'create venv'
    if ($rc -ne 0) {
        Write-Fail ('创建 venv 失败（exit=' + $rc + '）。确认 Python 可用且有权写入 ' + $VenvDir)
    }
    if (-not $DryRun) {
        if (-not (Test-Path -LiteralPath $VenvPython -PathType Leaf)) {
            Write-Fail ('venv 创建后仍找不到 ' + $VenvPython)
        }
        Write-Ok ('已创建 venv: ' + $VenvPython)
    }
}

# ---------------------------------------------------------------------------
# 3. 安装依赖
# ---------------------------------------------------------------------------
Write-Step '安装 Python 依赖'

if ($SkipPip) {
    Write-Warn '已跳过 pip install（-SkipPip）'
} else {
    if (-not (Test-Path -LiteralPath $Requirements -PathType Leaf)) {
        Write-Fail ('找不到依赖清单: ' + $Requirements)
    }
    $pipArgs = @('-m', 'pip', 'install', '--disable-pip-version-check', '-r', $Requirements)
    $rc = Invoke-Native -FilePath $VenvPython -Arguments $pipArgs -Display 'pip install'
    if ($rc -ne 0) {
        Write-Fail ('pip install 失败（exit=' + $rc + '）。可尝试：' + $VenvPython + ' -m pip install -r ' + $Requirements + ' -i https://pypi.tuna.tsinghua.edu.cn/simple')
    }
    if (-not $DryRun) {
        Write-Ok '依赖安装完成'
    }
}

# ---------------------------------------------------------------------------
# 4. 冒烟测试
# ---------------------------------------------------------------------------
Write-Step '冒烟测试 mcp_4nec2_server.py --version'

if ($DryRun) {
    Write-Plan ($VenvPython + ' ' + $ServerScript + ' --version')
} elseif (Test-Path -LiteralPath $VenvPython -PathType Leaf) {
    $prevEap = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $versionOut = & $VenvPython $ServerScript --version 2>&1
        $versionCode = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $prevEap
    }
    if ($versionCode -ne 0) {
        Write-Fail ('--version 执行失败（exit=' + $versionCode + '）：' + (($versionOut | Out-String).Trim()))
    }
    Write-Ok ('服务可执行，版本输出: ' + (($versionOut | Out-String).Trim()))
} else {
    Write-Warn 'venv 尚不存在，跳过冒烟测试'
}

# ---------------------------------------------------------------------------
# 5. 生成启动器
# ---------------------------------------------------------------------------
Write-Step '生成启动器脚本'

if (-not (Test-Path -LiteralPath $ScriptsDir -PathType Container)) {
    if ($DryRun) {
        Write-Plan ('新建目录 ' + $ScriptsDir)
    } else {
        New-Item -ItemType Directory -Path $ScriptsDir -Force | Out-Null
    }
}

$stdioBat = Join-Path $ScriptsDir 'start-stdio.bat'
$httpBat = Join-Path $ScriptsDir 'start-http.bat'

Write-BatchFile -Path $stdioBat -Title '4NEC2 MCP Server - stdio transport (for DSH / MCP clients)' -Mode 'stdio'
Write-BatchFile -Path $httpBat -Title ('4NEC2 MCP Server - HTTP transport, endpoint http://' + $HttpHost + ':' + $HttpPort + '/mcp') -Mode 'http'

# ---------------------------------------------------------------------------
# 6. DSH 配置条目
# ---------------------------------------------------------------------------
if (-not $NoDsh) {
    Write-Step 'DSH 配置条目（@deepseek-ai/dsh-mcp-client）'

    $dshEntry = @"
- id: mcp-nec2
  name: "@deepseek-ai/dsh-mcp-client"
  config:
    serverName: nec2
    transport: stdio
    command: $VenvPython
    args: ['$ServerScript', '--4nec2-dir', '$Nec2DirPath']
    cwd: $ProjectDirPath
    env:
      PYTHONUTF8: '1'
      PYTHONIOENCODING: 'utf-8'
      NEC4NEC_DIR: '$Nec2DirPath'
      NEC2_ENGINE: '$EnginePath'
    toolCallTimeoutMs: 300000
    failOnStartupError: false
"@

    Write-Host ''
    Write-Host '  把下面这段追加到 cordis.patch.yml 顶层数组末尾（顶格、与现有条目同级）：' -ForegroundColor White
    Write-Host ''
    Write-Host $dshEntry -ForegroundColor Gray
    Write-Host ('  目标文件: ' + $DshConfig) -ForegroundColor White
    Write-Host '  说明: args 使用单引号是刻意的 —— YAML 双引号里的 \4 会被当成非法转义序列，' -ForegroundColor DarkGray
    Write-Host '        用单引号（或不加引号）可保证 Windows 路径原样传递。' -ForegroundColor DarkGray
    Write-Host '  提示: DSH 编辑该配置项后会原地重载 MCP 连接，无需重启 harness。' -ForegroundColor DarkGray

    $applyNow = $ApplyDsh -and (-not $DryRun)

    if ($ApplyDsh -and $DryRun) {
        Write-Warn 'DryRun 模式：不写入 cordis.patch.yml。'
    }

    if ($applyNow) {
        Write-Step '写入 cordis.patch.yml'

        if (-not (Test-Path -LiteralPath $ProfileDirPath -PathType Container)) {
            Write-Fail ('DSH 配置目录不存在: ' + $ProfileDirPath + '（用 -ProfileDir 指定）')
        }

        if (-not (Test-Path -LiteralPath $DshConfig -PathType Leaf)) {
            Write-Warn ('配置文件不存在，将新建: ' + $DshConfig)
            $existing = ''
        } else {
            $existing = [System.IO.File]::ReadAllText($DshConfig, [System.Text.Encoding]::UTF8)
        }

        $hasEntry = [regex]::IsMatch($existing, '(?m)^\s*-\s*id:\s*''?mcp-(nec2|4nec2)''?\s*$')
        $hasServer = [regex]::IsMatch($existing, '(?m)^\s*serverName:\s*''?nec2''?\s*$')

        if ($hasEntry) {
            Write-Warn '已存在 id: mcp-nec2 / mcp-4nec2，跳过写入（如需更新请手工编辑）。'
        } elseif ($hasServer) {
            Write-Warn '已存在 serverName: nec2 的其他实例，跳过写入以避免重名。'
        } else {
            $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
            if ($existing.Length -gt 0) {
                $backup = $DshConfig + '.bak-' + $stamp
                Copy-Item -LiteralPath $DshConfig -Destination $backup
                Write-Ok ('已备份原配置: ' + $backup)
            }

            $newline = "`n"
            if ($existing -like "*`r`n*") {
                $newline = "`r`n"
            }

            $body = $dshEntry -replace "`r`n", "`n"
            $body = $body -replace "`n", $newline

            if ($existing.Length -eq 0) {
                $merged = $body + $newline
            } else {
                if (-not ($existing.EndsWith("`n"))) {
                    $existing = $existing + $newline
                }
                $merged = $existing + $body + $newline
            }

            [System.IO.File]::WriteAllText($DshConfig, $merged, (Get-Utf8NoBom))
            Write-Ok ('已写入条目: ' + $DshConfig)
            Write-Warn 'DSH 会重载该配置；重载失败时用备份回滚。'
        }
    } elseif (-not $NoDsh -and -not $ApplyDsh) {
        Write-Host ''
        Write-Host '  当前为"只打印"模式：未修改任何 DSH 配置。' -ForegroundColor Yellow
        Write-Host '  确认无误后，加 -ApplyDsh 重跑本脚本即可自动写入（含备份与幂等检查）：' -ForegroundColor Yellow
        Write-Host ('    powershell -NoProfile -ExecutionPolicy Bypass -File ' + (Join-Path $ScriptsDir 'install.ps1') + ' -ApplyDsh') -ForegroundColor Yellow
    }
}

# ---------------------------------------------------------------------------
# 7. 完成
# ---------------------------------------------------------------------------
Write-Step '完成'
Write-Host ''
Write-Host '  已生成/更新：' -ForegroundColor White
Write-Info ('  ' + $VenvPython)
Write-Info ('  ' + $stdioBat)
Write-Info ('  ' + $httpBat)
Write-Host ''
Write-Host '  下一步验证：' -ForegroundColor White
Write-Info ('  ' + $VenvPython + ' ' + (Join-Path $ScriptsDir 'check-tools.py'))
Write-Info ('  ' + $VenvPython + ' ' + (Join-Path $ScriptsDir 'check-tools.py') + ' --call nec_list_engines')
Write-Info ('  ' + $VenvPython + ' ' + $ServerScript + ' --version')
Write-Host ''
Write-Host '  DSH 中的工具名形如：mcp__nec2__nec_run（见 docs\DSH-接入说明.md）' -ForegroundColor White
Write-Host ''

if ($DryRun) {
    Write-Host 'DryRun 结束：未做任何实际更改。' -ForegroundColor Yellow
} else {
    Write-Host '安装脚本执行完毕。' -ForegroundColor Green
}
exit 0
